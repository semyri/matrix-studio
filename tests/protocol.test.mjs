import assert from 'node:assert/strict';
import {command, rgbBytes, transmit} from '../docs/protocol.mjs';
const frame=Array(256).fill('#000000');
assert.deepEqual([...command([0xff,1])],[0xbc,0xff,1,0,0x55], 'Power command CRC wraps at 256');
assert.deepEqual([...command(Array(19).fill(1))],[0xbc,...Array(19).fill(1),19], 'Firmware omits the end byte at this framing boundary');
frame[0]='#ff0000';frame[31]='#00ff00';frame[32]='#0000ff';frame[255]='#ffffff';
const rgb=rgbBytes(frame,1);
assert.equal(rgb.length,768);assert.deepEqual(rgb.slice(0,3),[255,0,0]);assert.deepEqual(rgb.slice(93,99),[0,255,0,0,0,255]);assert.deepEqual(rgb.slice(-3),[255,255,255]);
let writes=[];
const options={gamma:1,pause:async()=>{}};
assert.equal(await transmit([frame],async bytes=>writes.push([...bytes]),options),10);
assert.deepEqual(writes[0],[0xbc,15,241,8,8,85]);
assert.equal(writes[1].length,101);assert.deepEqual(writes[1].slice(0,6),[0xbc,15,1,255,0,0]);
assert.deepEqual(writes[2].slice(0,6),[0xbc,15,2,0,0,255]);
assert.deepEqual(writes.at(-1),[0xbc,15,242,8,9,85]);
assert.ok(!writes.some(b=>b[1]===0&&b[2]===21),'Temporary sending never resets saved artwork');
writes=[];await transmit([frame,Array(256).fill('#ff0000')],async bytes=>writes.push([...bytes]),options);
const blocks=writes.filter(b=>b[1]===2&&b[2]>=1&&b[2]<=8&&b[3]>=1&&b[3]<=8);
assert.equal(blocks.length,64,'Native animations populate all eight device slots');
assert.deepEqual(blocks.filter(b=>b[3]===1).map(b=>b[2]),[1,2,3,4,5,6,7,8]);
assert.deepEqual(blocks[0].slice(4,100),blocks[16].slice(4,100),'Short animations repeat');
